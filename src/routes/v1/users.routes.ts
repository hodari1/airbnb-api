import { Router } from "express";
import {
  getAllUsers,
  getUserById,
  createUser,
  updateUser,
  deleteUser,
} from "../../controllers/users.controller";
import { getUsersStats } from "../../controllers/stats.controller";

const router = Router();

router.get("/stats", getUsersStats); // 👈 must be before /:id
